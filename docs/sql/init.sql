-- Seata 数据库初始化脚本
USE student_platform;

CREATE TABLE IF NOT EXISTS `undo_log` (
    `id` bigint NOT NULL AUTO_INCREMENT,
    `branch_id` bigint NOT NULL,
    `xid` varchar(100) NOT NULL,
    `context` varchar(128) NOT NULL,
    `rollback_info` longtext NOT NULL,
    `log_status` int NOT NULL,
    `log_created_at` datetime NOT NULL,
    `log_modified_at` datetime NOT NULL,
    UNIQUE KEY `ux_undo_log` (`xid`,`branch_id`)
) ENGINE=InnoDB AUTO_INCREMENT=1 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='AT transaction mode undo table';

CREATE TABLE IF NOT EXISTS `global_table` (
    `xid` varchar(128) NOT NULL,
    `transaction_id` bigint DEFAULT NULL,
    `status` tinyint NOT NULL COMMENT '0:running;1:commit;2:rollback;',
    `application_id` varchar(64) DEFAULT NULL,
    `transaction_service_group` varchar(64) DEFAULT NULL,
    `transaction_name` varchar(64) DEFAULT NULL,
    `timeout` int DEFAULT NULL,
    `begin_time` bigint DEFAULT NULL,
    `application_data` varchar(200) DEFAULT NULL,
    PRIMARY KEY (`xid`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Transaction information table';

CREATE TABLE IF NOT EXISTS `branch_table` (
    `branch_id` bigint NOT NULL,
    `xid` varchar(128) NOT NULL,
    `transaction_id` bigint DEFAULT NULL,
    `resource_group_id` varchar(32) DEFAULT NULL,
    `resource_id` varchar(256) DEFAULT NULL,
    `branch_type` varchar(8) DEFAULT NULL,
    `status` tinyint NOT NULL COMMENT '0:running;1:commit;2:rollback;',
    `begin_time` bigint DEFAULT NULL,
    `application_data` varchar(2000) DEFAULT NULL,
    `description` varchar(500) DEFAULT NULL,
    PRIMARY KEY (`branch_id`),
    KEY `idx_xid` (`xid`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Branch transaction information';

CREATE TABLE IF NOT EXISTS `lock_table` (
    `row_key` varchar(128) NOT NULL,
    `xid` varchar(96) DEFAULT NULL,
    `transaction_id` bigint DEFAULT NULL,
    `branch_id` bigint NOT NULL,
    `resource_id` varchar(256) DEFAULT NULL,
    `table_name` varchar(32) DEFAULT NULL,
    `pk` varchar(32) DEFAULT NULL,
    `status` tinyint NOT NULL COMMENT '0:locked;1:rollbacking;',
    `gmt_created` datetime DEFAULT NULL,
    `gmt_modified` datetime DEFAULT NULL,
    PRIMARY KEY (`row_key`),
    KEY `idx_gm_modified` (`gmt_modified`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Distribute lock table';

CREATE TABLE IF NOT EXISTS `distributed_lock` (
    `lock_key` varchar(64) NOT NULL DEFAULT '',
    `lock_value` varchar(64) NOT NULL DEFAULT '',
    `expire_time` datetime NOT NULL,
    PRIMARY KEY (`lock_key`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Distributed lock table';
